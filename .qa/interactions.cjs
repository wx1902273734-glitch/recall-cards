const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const root = path.resolve(__dirname, '..');
const dom = new JSDOM(fs.readFileSync(path.join(root, 'index.html'), 'utf8'), {url:'http://localhost/', runScripts:'outside-only'});
const w = dom.window;
w.scrollTo = () => {};
w.HTMLElement.prototype.scrollIntoView = () => {};
w.HTMLDialogElement.prototype.showModal = function(){this.open = true;};
w.HTMLDialogElement.prototype.close = function(){this.open = false;};
w.ResizeObserver = class {observe(){} disconnect(){}};
w.confirm = () => true;
const originals = [
  {id:'a',deck:'前端',question:'第一张',answer:'## 标题 A\n\n答案',tags:[],due:0,interval:2,reviews:0,pinned:true,deckPinned:true},
  {id:'b',deck:'前端',question:'第二张',answer:'## 标题 B\n\n答案',tags:[],due:Date.now()+86400000,interval:5,reviews:2},
  {id:'c',deck:'其他',question:'其他卡片',answer:'答案',tags:[],due:0,interval:0,reviews:0}
];
w.localStorage.setItem('recall-cards-v1',JSON.stringify(originals));
for(const file of ['vendor/marked.js','vendor/purify.js','content.js','app.js']) w.eval(fs.readFileSync(path.join(root,file),'utf8'));
const $ = selector => w.document.querySelector(selector);
const state = () => JSON.parse(w.localStorage.getItem('recall-cards-v1'));
async function run(){
  $('[data-deck="前端"]').click();
  assert.equal($('#deckFilter').value,'前端');
  assert.equal(w.document.querySelectorAll('.library-card').length,2);
  $('[data-pin="b"]').click();
  assert.equal($('.library-card').dataset.id,'b','newly pinned card moves above older pins');
  assert.equal($('[data-pin="b"]').getAttribute('aria-pressed'),'true');
  $('[data-pin="b"]').click();
  assert.equal($('.library-card').dataset.id,'a');
  const exported = w.deckExport('前端');
  assert.equal(exported.cards.length,2); assert.ok(exported.cards.every(card=>card.deck==='前端'));
  // Account for the explicit pin-toggle mutation when checking navigation.
  const beforeNavigation = state();
  $('.library-card[data-id="a"]').click();
  assert.equal($('#editorDialog').open,false);
  assert.equal($('#cardIndex').textContent,'1 / 2');
  assert.equal($('#outlinePanel').hidden,true);
  assert.equal($('#previousCard').disabled,true);
  $('#nextCard').click();
  assert.match($('#questionContent').textContent,/第二张/);
  assert.equal($('#nextCard').disabled,true);
  assert.deepEqual(state(),beforeNavigation,'navigation must not reschedule cards');
  $('#outlineToggle').click(); assert.equal($('#outlinePanel').hidden,false);
  assert.equal($('#headingOutline').querySelectorAll('button').length,0,'do not leak answer headings');
  $('#revealBtn').click();
  assert.match($('#headingOutline').textContent,/标题 B/);
  $('#previousCard').click();
  $('#editCurrentCard').click();
  $('#questionInput').value='第一张修改';
  $('#editorForm').dispatchEvent(new w.Event('submit',{cancelable:true}));
  assert.equal(state()[0].pinned,true);assert.equal(state()[0].deckPinned,true);
  assert.equal($('#cardIndex').textContent,'1 / 2','editing keeps review position');
  $('#revealBtn').click();
  assert.equal($('[data-rating="good"] span').textContent,'4 天');
  $('[data-rating="good"]').click();
  assert.equal(state()[0].reviews,1);
  $('#previousCard').click(); $('#revealBtn').click();
  assert.equal($('[data-rating="good"]').disabled,true,'returning must not count twice');
  $('#backToLibrary').click();
  $('.library-card .card-edit').click(); assert.equal($('#editorDialog').open,true);
  $('[data-close-dialog]').click();
  $('#deckFilter').value='其他'; $('#deckFilter').dispatchEvent(new w.Event('change'));
  $('#newCardBtn').click(); assert.equal($('#deckInput').value,'其他'); $('[data-close-dialog]').click();
  $('#importBtn').click();
  await w.importFiles([{name:'新内容.md',text:async()=> '## 导入内容'}]);
  assert.equal(state()[0].deck,'其他'); assert.equal(state().length,4);
  await w.importFiles([{name:'backup.json',text:async()=> JSON.stringify([{question:'JSON',answer:'A',deck:'旧牌组'}])}]);
  assert.equal(state()[0].deck,'其他'); assert.equal(state().length,5,'JSON import appends');
  await w.importFiles([{name:'doubao_qa.jsonl',text:async()=> '{"question":"JSONL 问题","answer":"JSONL 答案"}\n'}]);
  assert.equal(state()[0].question,'JSONL 问题'); assert.equal(state()[0].deck,'其他');
  const before = w.localStorage.getItem('recall-cards-v1');
  await w.importFiles([{name:'bad.json',text:async()=> '[{}]'}]);
  assert.equal(w.localStorage.getItem('recall-cards-v1'),before,'invalid import is atomic');
  $('#sidebarToggle').click();
  assert.equal(w.document.body.classList.contains('sidebar-collapsed'),true);
  assert.equal(w.localStorage.getItem('recall-sidebar-collapsed'),'true');
  $('#sidebarToggle').click(); assert.equal($('#sidebarToggle').getAttribute('aria-expanded'),'true');
  const sample = fs.readFileSync(path.join(__dirname,'pasted-text.md'),'utf8');
  const target = w.document.createElement('div');
  w.renderRichContent(target,sample);
  assert.equal(target.querySelectorAll('iframe').length,2);
  assert.equal(target.querySelectorAll('table').length,3);
  assert.equal(target.querySelector('table th').textContent.trim(),'');
  assert.ok(target.querySelectorAll('hr').length>0);
  assert.ok(target.querySelector('iframe').srcdoc.includes('Agent 概念全景'));
  console.log('PASS: review navigation, explicit editing, preserved metadata, deck imports, append/validation, outline, sidebar, pasted Markdown/HTML');
  w.close();
}
run().catch(error=>{console.error(error);w.close();process.exitCode=1;});
