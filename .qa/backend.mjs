import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync,readdirSync} from 'node:fs';
import worker from '../worker.js';
const db = new DatabaseSync(':memory:');
for (const file of readdirSync('drizzle').filter(f=>f.endsWith('.sql')).sort()) db.exec(readFileSync('drizzle/'+file,'utf8'));
const env = {DB:{prepare(sql){const query=db.prepare(sql);return {first:()=>query.get(),bind(...args){return {run:()=>({meta:query.run(...args)})};}};}}};
const request = (body,origin) => worker.fetch(new Request('https://example.com/api/cards',body === undefined ? {} : {method:'PUT',headers:{'Content-Type':'application/json',...(origin?{Origin:origin}:{})},body:JSON.stringify(body)}),env);
assert.deepEqual(await (await request()).json(),{revision:0,cards:[]});
const card={id:'a',deck:'示例',question:'Q',answer:'A',tags:[],due:0,interval:0,reviews:0,pinned:true};
assert.equal((await request({revision:0,cards:[card]})).status,200);
assert.equal((await request({revision:0,cards:[]})).status,409);
assert.deepEqual((await (await request()).json()).cards,[card]);
assert.equal((await request({revision:1,cards:[{}]})).status,400);
assert.equal((await request({revision:1,cards:[]},'https://elsewhere.com')).status,403);
assert.equal((await request({revision:1,cards:[]})).status,200);
assert.deepEqual(await (await request()).json(),{revision:2,cards:[]});
assert.equal((await worker.fetch(new Request('https://example.com/'),env)).status,200);
assert.equal((await worker.fetch(new Request('https://example.com/.env'),env)).status,404);
assert.deepEqual(await (await worker.fetch(new Request('https://example.com/api/health'),{...env,APP_TOKEN:'secret'})).json(),{ok:true,authRequired:true});
assert.equal((await worker.fetch(new Request('https://example.com/api/cards'),{...env,APP_TOKEN:'secret'})).status,401);
assert.equal((await worker.fetch(new Request('https://example.com/api/cards',{headers:{Authorization:'Bearer secret'}}),{...env,APP_TOKEN:'secret'})).status,200);
db.close();console.log('PASS: persistence, revision conflicts, deletion, validation, origin checks, static allowlist');
